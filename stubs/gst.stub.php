{
    public int $flags = 0;

    public string $data = "";

    public int $size = 0;

    public int $maxsize = 0;

    public function __construct() {}
}

/**
 * Handles are made by the bound functions. Dropping the PHP object does not unref the native
 * object. fromPointer() trusts any address other than 0. The top class: no GObject class, as
 * ext-gtk owns that PHP class name.
