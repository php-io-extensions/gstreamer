<?php

declare(strict_types=1);

/*
 * The support list: every function the public headers of the five bound GStreamer modules
 * (gstreamer, gstreamer-app, gstreamer-video, gstreamer-audio, gstreamer-pbutils) declare at the
 * floor tag (1.26.2, Debian trixie), marked bound when a stub declares the PHP function of the same
 * name. GStreamer 1.x never removes API, so the floor's functions are the ones every supported
 * GStreamer has; a function a later release added cannot be bound and still build on the floor.
 *
 *   php84 scripts/support.php           writes SUPPORT.md and the README badge
 *   php84 scripts/support.php --check   exits 1 when either differs (the date is not compared)
 *
 * The headers come from the GStreamer monorepo at the tag (the module directories below, private
 * headers left out), cached under scripts/.support-cache/. A member is a function its header
 * exports with GST_API / GST_<MODULE>_API, or defines as static inline.
 */

const SUPPORT_LABEL = 'GStreamer API';
const SUPPORT_FLOOR = '1.26.2';
const SUPPORT_REPO = 'GStreamer/gstreamer';
/** Monorepo directory => the include path its headers install under. */
const SUPPORT_MODULES = [
    'subprojects/gstreamer/gst' => 'gst',
    'subprojects/gst-plugins-base/gst-libs/gst/app' => 'gst/app',
    'subprojects/gst-plugins-base/gst-libs/gst/video' => 'gst/video',
    'subprojects/gst-plugins-base/gst-libs/gst/audio' => 'gst/audio',
    'subprojects/gst-plugins-base/gst-libs/gst/pbutils' => 'gst/pbutils',
];

/** C source without comments and preprocessor lines. */
function support_code(string $source): string
{
    $source = preg_replace('~/\*.*?\*/~s', ' ', $source);
    $source = preg_replace('~//[^\n]*~', ' ', $source);
    $source = preg_replace('/\\\\\n/', ' ', $source);

    return preg_replace('/^\s*#[^\n]*/m', ' ', $source);
}

/** The gst_ functions one header exports or defines static inline. @return list<string> */
function support_header_functions(string $source): array
{
    $code = support_code($source);
    preg_match_all('/\bGST_(?:[A-Z]+_)?API\b[^;{]*?\b(gst_[a-z0-9_]+)\s*\(/', $code, $exported);
    preg_match_all('/\bstatic\s+inline\b[^;{(]*?\b(gst_[a-z0-9_]+)\s*\(/', $code, $inline);
    $names = array_values(array_unique(array_merge($exported[1], $inline[1])));
    sort($names, SORT_STRING);

    return $names;
}

/** @return array<string, list<string>> include path of each header => its functions, empty headers left out */
function support_counted(array $headers): array
{
    $counted = [];
    foreach ($headers as $path => $source) {
        $functions = support_header_functions($source);
        if ($functions !== []) {
            $counted[$path] = $functions;
        }
    }
    ksort($counted, SORT_STRING);

    return $counted;
}

/** @return array<string, true> the functions the stubs declare */
function support_bound(string $stubs): array
{
    $bound = [];
    foreach (glob("{$stubs}/*.stub.php") as $stub) {
        preg_match_all('/^function\s+([a-z_][a-z0-9_]*)\s*\(/m', file_get_contents($stub), $m);
        foreach ($m[1] as $name) {
            $bound[$name] = true;
        }
    }
    ksort($bound, SORT_STRING);

    return $bound;
}

function support_render(array $counted, array $bound, string $date): string
{
    $sections = [];
    $countedKeys = [];
    $hits = 0;
    $total = 0;
    foreach ($counted as $header => $functions) {
        $lines = [];
        $headerHits = 0;
        foreach ($functions as $function) {
            $countedKeys[$function] = true;
            $isBound = isset($bound[$function]);
            $headerHits += $isBound ? 1 : 0;
            $lines[] = '- [' . ($isBound ? 'x' : ' ') . "] `{$function}`";
        }
        $hits += $headerHits;
        $total += count($functions);
        $sections[] = "## {$header} ({$headerHits} / " . count($functions) . ")\n\n" . implode("\n", $lines) . "\n";
    }
    $outside = array_map(static fn (string $f): string => "- `{$f}`", array_keys(array_diff_key($bound, $countedKeys)));

    return '# ' . SUPPORT_LABEL . " support\n\n"
        . support_summary($hits, $total, $date) . "\n\n"
        . 'Generated by `php84 scripts/support.php` from the public headers of GStreamer ' . SUPPORT_FLOOR
        . " (gstreamer, app, video, audio, pbutils) and `stubs/`. One line per function: `[x]` bound, `[ ]` not bound.\n\n"
        . implode("\n", $sections)
        . "\n## Bound outside the counted functions\n\n"
        . "Functions the stubs declare that the counted headers do not export as functions (a macro in C); none of them is counted.\n\n"
        . (count($outside) === 0 ? "None.\n" : implode("\n", $outside) . "\n");
}

function support_summary(int $hits, int $total, string $date): string
{
    return sprintf('GStreamer %s — %d / %d members bound (%.1f%%) — %s', SUPPORT_FLOOR, $hits, $total, $total === 0 ? 0 : 100 * $hits / $total, $date);
}

function support_badge(int $bound, int $total): string
{
    $percent = sprintf('%.1f', $total === 0 ? 0 : 100 * $bound / $total);
    $message = str_replace('%20', '_', rawurlencode("{$percent}% ({$bound}/{$total})"));

    return '[![' . SUPPORT_LABEL . '](https://img.shields.io/badge/' . str_replace(' ', '_', SUPPORT_LABEL) . "-{$message}-blue?style=flat-square)](SUPPORT.md)";
}

/** Two support lists alike but for the date of their summary line. */
function support_same(string $a, string $b): bool
{
    $undated = static fn (string $s): string => preg_replace('/ — \d{4}-\d{2}-\d{2}$/m', '', $s);

    return $undated($a) === $undated($b);
}

/** The README with the badge line set: replaced where it is, else after the CI badge. */
function support_readme(string $readme, string $badge): string
{
    $lines = explode("\n", $readme);
    foreach ($lines as $i => $line) {
        if (str_starts_with($line, '[![' . SUPPORT_LABEL . ']')) {
            $lines[$i] = $badge;

            return implode("\n", $lines);
        }
    }
    foreach ($lines as $i => $line) {
        if (str_starts_with($line, '[![CI]')) {
            array_splice($lines, $i + 1, 0, [$badge]);

            return implode("\n", $lines);
        }
    }
    throw new RuntimeException('The README has no CI badge line to put the API badge after.');
}

/** @return array{int, int} bound and total, read back from a support list's summary line */
function support_totals(string $md): array
{
    preg_match('/ (\d+) \/ (\d+) members bound/', $md, $m);

    return [(int) $m[1], (int) $m[2]];
}

/** A pinned upstream file, downloaded once into the cache. */
function support_fetch(string $url, string $cache): string
{
    if (! is_file($cache)) {
        $context = stream_context_create(['http' => ['header' => "User-Agent: php-io-extensions-support\r\n"]]);
        $body = @file_get_contents($url, false, $context);
        if ($body === false) {
            throw new RuntimeException("Cannot download {$url}.");
        }
        @mkdir(dirname($cache), 0777, true);
        file_put_contents($cache, $body);
    }

    return file_get_contents($cache);
}

/** @return array<string, string> include path (gst/app/gstappsink.h) => source, the public headers of the bound modules at the floor */
function support_headers(string $cache): array
{
    $tree = json_decode(support_fetch(
        'https://api.github.com/repos/' . SUPPORT_REPO . '/git/trees/' . SUPPORT_FLOOR . '?recursive=1',
        "{$cache}/" . SUPPORT_FLOOR . '/tree.json',
    ), true);
    if (! is_array($tree) || ! isset($tree['tree']) || ($tree['truncated'] ?? false)) {
        throw new RuntimeException('The GitHub tree of ' . SUPPORT_FLOOR . ' is missing or truncated.');
    }
    $headers = [];
    foreach ($tree['tree'] as $entry) {
        $path = $entry['path'];
        $dir = dirname($path);
        $name = basename($path);
        if ($entry['type'] !== 'blob' || ! isset(SUPPORT_MODULES[$dir]) || ! str_ends_with($name, '.h') || str_contains($name, 'private')) {
            continue;
        }
        $headers[SUPPORT_MODULES[$dir] . "/{$name}"] = support_fetch(
            'https://raw.githubusercontent.com/' . SUPPORT_REPO . '/' . SUPPORT_FLOOR . "/{$path}",
            "{$cache}/" . SUPPORT_FLOOR . "/{$path}",
        );
    }

    return $headers;
}

function support_main(array $argv): int
{
    $root = dirname(__DIR__);
    try {
        $counted = support_counted(support_headers("{$root}/scripts/.support-cache"));
    } catch (RuntimeException $e) {
        fwrite(STDERR, $e->getMessage() . "\n");

        return 2;
    }
    $md = support_render($counted, support_bound("{$root}/stubs"), date('Y-m-d'));
    [$hits, $total] = support_totals($md);
    $readme = support_readme(file_get_contents("{$root}/README.md"), support_badge($hits, $total));

    if (in_array('--check', $argv, true)) {
        $current = is_file("{$root}/SUPPORT.md") ? file_get_contents("{$root}/SUPPORT.md") : '';
        $same = support_same($current, $md) && $readme === file_get_contents("{$root}/README.md");
        fwrite(STDOUT, $same ? "SUPPORT.md and the badge are current.\n" : "SUPPORT.md or the badge differs: run php84 scripts/support.php.\n");

        return $same ? 0 : 1;
    }
    file_put_contents("{$root}/SUPPORT.md", $md);
    file_put_contents("{$root}/README.md", $readme);
    fwrite(STDOUT, "{$hits} / {$total}\n");

    return 0;
}

if (PHP_SAPI === 'cli' && isset($argv[0]) && realpath($argv[0]) === __FILE__) {
    exit(support_main($argv));
}
